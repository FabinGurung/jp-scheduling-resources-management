import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { resolve, extname } from 'node:path';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const production = process.argv[2];
const server = createServer(async (req, res) => {
  const path = new URL(req.url, 'http://127.0.0.1').pathname;
  try {
    const route = path.replace(/^\/schedules\//, '');
    if (route.startsWith('/') || route.split('/').includes('..')) throw Error('Invalid preview route');
    const name = resolve('dist-v2', route + (path.endsWith('/') ? 'index.html' : ''));
    const mime = {'.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json'};
    res.setHeader('Content-Type', mime[extname(name)] ?? 'application/octet-stream');
    res.end(await readFile(name));
  } catch {
    res.statusCode = 404;
    res.end();
  }
});
await new Promise(done => server.listen(0, '127.0.0.1', done));
const root = production ?? 'http://127.0.0.1:' + server.address().port + '/schedules/';
const browser = await chromium.launch({args: ['--no-sandbox']});
try {
  for (const width of [1440, 1024, 768, 390]) {
    const page = await browser.newPage({viewport: {width, height: 900}, isMobile: width < 500, hasTouch: width < 500});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on("console",msg=>{if(msg.type()==="error")console.log("Browser console:",msg.text())});
    const directory = await page.goto(root + 'projects/index.html', {waitUntil: 'domcontentloaded'});
    assert.equal(directory.status(), 200);
    await page.locator("skyforge-foreman").waitFor();
    assert.equal(await page.locator("skyforge-foreman").count(),1);
    await page.getByRole('button',{name:'Hide Foreman'}).click();
    await page.getByRole('button',{name:'Show Foreman'}).waitFor();
    await page.getByRole('button',{name:'Show Foreman'}).click();
    await page.getByText('22 projects found').waitFor();
    await page.locator('#search').fill('Narayani');
    assert.equal(await page.locator('.project-card').count(), 1);
    await page.getByRole('link', {name: /Narayani Parajuli/}).click();
    await page.getByRole('heading', {name: 'Narayani Parajuli Residence'}).waitFor();
    await page.getByText('This schedule is a planning draft.', {exact: false}).waitFor();
    assert.match(await page.locator('#view').innerText(), /of 160 activities/);
    await page.getByRole('tab', {name: 'Gantt'}).click();
    await page.waitForURL(/gantt\.html\?project=PORT-000001/);
    await page.locator('.gantt-bar').first().waitFor();
    assert.equal(await page.locator('.gantt-bar').count(), 50);
    assert.equal(await page.locator(".planner-chart").getAttribute("data-scale"),"week");
    await page.getByRole("combobox",{name:"Gantt timescale"}).selectOption("day");
    assert.equal(await page.locator(".planner-chart").getAttribute("data-scale"),"day");
    await page.getByRole("button",{name:"Work-stage overview"}).click();
    assert.ok(await page.locator(".gantt-summary-row").count()>0);
    await page.getByRole("button",{name:"Activity detail"}).click();
    await page.getByRole("combobox",{name:"Gantt timescale"}).selectOption("week");
    assert.ok(await page.locator('.dependency-line').count()>0,"Missing dependency arrows");
    assert.ok(await page.locator('.dependency-line').evaluateAll(lines=>lines.every(l=>/^(FS|SS|FF|SF)$/.test(l.dataset.type)&&l.dataset.from&&l.dataset.to)));
    await page.getByRole('button',{name:'Hide dependency lines'}).click();
    assert.equal(await page.locator('.dependency-line').count(),0);
    await page.getByRole('button',{name:'Show dependency lines'}).click();
    await page.locator('.dependency-line').first().waitFor({state:'attached'});
    await page.locator(".gantt-scroll").scrollIntoViewIfNeeded();
    await page.waitForFunction(()=>document.querySelector("skyforge-foreman")?.dataset.mode==="gantt");
    const before=await page.locator("skyforge-foreman").getAttribute("data-y");
    await page.waitForFunction(y=>document.querySelector("skyforge-foreman")?.dataset.y!==y,before,{timeout:10000});
    assert.equal(await page.locator("skyforge-foreman").evaluate(el=>getComputedStyle(el).pointerEvents),"none");
    await page.getByRole('tab', {name: 'Calendar'}).click();
    await page.waitForURL(/calendar\.html/);
    await page.locator('.calendar-days button').first().waitFor();
    assert.equal(await page.locator('.calendar-days button').count(), 7);
    await page.getByRole('button',{name:'Compact / zoom out'}).click();
    assert.ok(await page.locator('.calendar-compact').count());
    await page.getByRole('button',{name:'Show 4 weeks'}).click();
    assert.equal(await page.locator('.calendar-days button').count(),28);
    await page.locator('.calendar-days button').first().scrollIntoViewIfNeeded();
    await page.waitForFunction(()=>document.querySelector("skyforge-foreman")?.dataset.mode==="calendar");
    assert.ok(await page.locator(".calendar-count").evaluateAll(nodes=>nodes.every(e=>!e.textContent.includes("scheduled"))));
    await page.locator('.calendar-days button').first().click();
    assert.equal(await page.locator('.calendar-days button[aria-pressed=true]').count(),1);
    await page.locator('#inspector h3').getByText('Relative day 0').waitFor();
    if(width<=1130)assert.ok(await page.evaluate(()=>document.querySelector('#detailsPane').getBoundingClientRect().top>=document.querySelector('.centre').getBoundingClientRect().bottom-2),'Selected details must sit below main view');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Calendar page has horizontal overflow');
    await page.getByRole('tab',{name:'Planning control'}).click();
    await page.getByRole('heading',{name:'Lookahead and readiness'}).waitFor();
    await page.locator(".control-lookahead table").waitFor();
    await page.getByRole('combobox',{name:'Lookahead span'}).selectOption("7");
    assert.ok(await page.locator(".control-lookahead").innerText().then(t=>t.includes("scheduled activities")));
    await page.getByRole('heading',{name:'Network and float diagnostic'}).waitFor();
    await page.getByRole('heading',{name:'Baseline, actual progress and resources'}).waitFor();
    await page.getByRole('tab', {name: 'Work packages'}).click();
    await page.getByRole('button', {name: 'Show package'}).waitFor();
    await page.getByRole('tab', {name: 'Drawing packages'}).click();
    await page.waitForURL(/drawings\.html/);
    await page.getByRole('link', {name: 'Open drawing library'}).waitFor();
    await page.goto(root + 'projects/activities.html?project=PORT-000014');
    await page.getByRole('heading', {name: 'Harisharan Residence'}).waitFor();
    assert.match(await page.locator('#view').innerText(), /of 839 activities/);
    await page.goto(root + 'projects/view.html?project=PORT-000019');
    await page.getByText('No activity schedule is available for this selection.').waitFor();
    await page.goto(root + 'resources/index.html');
    await page.getByRole('link', {name: 'Open materials planner'}).waitFor();
    const headings = await page.locator('#resourceList th').allTextContents();
    assert.deepEqual(headings, ['Reference work', 'Category', 'Unit', 'Per work unit'],
      'Resource table headers at ' + width + 'px');
    assert.ok(await page.locator('#resourceList tbody tr').count() > 0);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.goto(root + 'resources/modules.html');
    await page.getByRole('button',{name:/Brick masonry/}).first().waitFor();
    await page.getByRole('heading',{name:'Readiness checklist'}).waitFor();
    await page.locator('#moduleSearch').fill('slab');
    assert.ok(await page.locator('#moduleList button').count()>=1);
    await page.goto(root + 'resources/sources.html');
    await page.getByText('48 automatically read files',{exact:false}).waitFor();
    assert.match(await page.getByRole('link',{name:'Exact project Doc, Sheet & folder links'}).getAttribute('href'),/#gid=102$/);
    assert.match(await page.getByRole('link',{name:'Open synchronized Drive'}).getAttribute('href'),/drive\.google\.com\/drive\/folders\//);
    await page.locator('#sourceSearch').fill('Narayani');
    assert.equal(await page.locator('#sourceList tbody tr').count(),2);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
    assert.deepEqual(errors, []);
    await page.close();
    console.log(width + 'px: 22 projects, public Doc notes, all five views, empty source state and rate/norm search pass');
  }
} finally {
  await browser.close();
  server.close();
}
